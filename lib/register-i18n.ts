export const STRINGS: Record<Lang, RegisterStrings> = {
  en, es, fr, de, it, pt, pl, el, ru, vi, tl, zh, 'zh-hant': zhHant, ko, hi, pa,
}

const LANG_STORAGE_KEY = 'ohaccess_lang'

// Best-guess starting language: a previously chosen one wins, else the
// device language, else English. Safe to call only in the browser.
export function detectLang(): Lang {
  try {
    const saved = window.localStorage.getItem(LANG_STORAGE_KEY)
    if (saved && saved in STRINGS) return saved as Lang
  } catch { /* storage blocked — fall through to device language */ }
  const device = (navigator.language || '').toLowerCase()
  // Chinese needs a script decision: Traditional for Taiwan/Hong Kong/Macau
  // (or an explicit -Hant tag), Simplified for the rest of zh-*.
  if (device.startsWith('zh')) {
    if (device.includes('hant') || device.startsWith('zh-tw') || device.startsWith('zh-hk') || device.startsWith('zh-mo')) return 'zh-hant'
    return 'zh'
  }
  for (const { code } of LANGS) {
    if (code !== 'en' && code !== 'zh' && code !== 'zh-hant' && device.startsWith(code)) return code
  }
  return 'en'
}

export function saveLang(code: Lang): void {
  try { window.localStorage.setItem(LANG_STORAGE_KEY, code) } catch { /* best effort */ }
}
